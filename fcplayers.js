// Get every player
function getFCPlayers() {

  return fcplayers;

}


// Get players by position
function getPlayersByPosition(position) {

  return fcplayers.filter(player =>
    Array.isArray(player.positions) &&
    player.positions.includes(position)
  );

}


// Search players by name
function searchFCPlayers(searchText) {

  const query =
    String(searchText || "")
      .trim()
      .toLowerCase();


  if (query === "") {

    return fcplayers;

  }


  return fcplayers.filter(player =>

    String(player.name || "")
      .toLowerCase()
      .includes(query)

  );

}


// Search players by name + OVR
function searchFCPlayersByOVR(searchText, ovr) {

  const query =
    String(searchText || "")
      .trim()
      .toLowerCase();


  return fcplayers.filter(player => {

    const nameMatch =
      query === "" ||
      String(player.name || "")
        .toLowerCase()
        .includes(query);


    const ovrMatch =
      ovr === "" ||
      ovr === null ||
      ovr === undefined ||
      Number(player.ovr) === Number(ovr);


    return nameMatch && ovrMatch;

  });

}


// Get players by OVR
function getPlayersByOVR(ovr) {

  return fcplayers.filter(player =>
    Number(player.ovr) === Number(ovr)
  );

}


// Get players by OVR range
function getPlayersByOVRRange(minOVR, maxOVR) {

  return fcplayers.filter(player =>
    Number(player.ovr) >= Number(minOVR) &&
    Number(player.ovr) <= Number(maxOVR)
  );

}


// Get players by position + OVR
function getPlayersByPositionAndOVR(position, ovr) {

  return fcplayers.filter(player =>

    Array.isArray(player.positions) &&
    player.positions.includes(position) &&
    Number(player.ovr) === Number(ovr)

  );

}


// Get unique player names
function getUniqueFCPlayerNames() {

  return [

    ...new Set(
      fcplayers.map(player =>
        player.name
      )
    )

  ];

}


// Get all available positions
function getFCPositions() {

  return [

    ...new Set(

      fcplayers.flatMap(player =>

        Array.isArray(player.positions)
          ? player.positions
          : []

      )

    )

  ];

}


